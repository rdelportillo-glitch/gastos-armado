-- ============================================================================
-- Maestro de viáticos por municipio (Maestros > Viáticos por municipio): valor del viático que se envía según el departamento y el municipio.
--   - public.viatico_municipios: departamento, municipio, "gasto viático" (ENVIAR...) y valor en pesos. No se borran: se anulan (active = false).
--   - Carga inicial con la hoja entregada (136 municipios). Si el municipio ya existe (mismo departamento y municipio) no se duplica ni se pisa.
-- Solo crea una tabla nueva; no modifica ni borra datos existentes. Se puede correr más de una vez.
-- ============================================================================

create table if not exists public.viatico_municipios (
  id uuid primary key default gen_random_uuid(),
  department text not null,
  municipality text not null,
  expense_action text not null default 'ENVIAR',
  value numeric not null default 0 check (value >= 0),
  active boolean not null default true,
  created_at timestamptz not null default now()
);
create unique index if not exists viatico_municipios_unique on public.viatico_municipios (upper(btrim(department)), upper(btrim(municipality)));

alter table public.viatico_municipios enable row level security;
drop policy if exists "viatico_municipios_select_all" on public.viatico_municipios;
drop policy if exists "viatico_municipios_insert_admin" on public.viatico_municipios;
drop policy if exists "viatico_municipios_update_admin" on public.viatico_municipios;
-- Cualquier usuario activo los lee; solo un administrador crea o edita. No hay DELETE.
create policy "viatico_municipios_select_all" on public.viatico_municipios for select using (public.is_active_user());
create policy "viatico_municipios_insert_admin" on public.viatico_municipios for insert with check (public.current_role() = 'admin');
create policy "viatico_municipios_update_admin" on public.viatico_municipios for update using (public.current_role() = 'admin') with check (public.current_role() = 'admin');

